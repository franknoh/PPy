"""Generated CPython-ABI wrappers for native functions (spec 16.4, 16.5).

A compiled PPY function has two entry points. Statically compiled PPY callers
use the native ABI directly. Python callers go through the wrapper generated
here, which parses arguments, applies the guards, invokes the native code, and
boxes the result -- using the version-specific CPython C API, because that is
what makes the boundary cheap enough for the native path to be worth taking.

A guard that fails returns `NotImplemented`, which is the signal to re-run the
original Python implementation.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from ppy_runtime.abi import CrossingClass
from ppy_runtime.collection_boundary import Spec, field_spec
from ppy_runtime.collection_boundary import parse as parse_spec

from .lowering import NativeParam, NativeSignature

